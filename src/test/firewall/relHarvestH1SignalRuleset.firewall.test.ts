/**
 * REL HARVEST H1 FIREWALL - discovery-subject runs score under
 * orgunit-signal-rules-v2; every ECHE run stays on v1, byte for byte.
 *
 * Ported from the duplicate relf1 line (`362e973`, REL-F1-R2 Wave 2 item a)
 * onto the rel-* design; none of relf1's migrations came with it. Over
 * H1_BASE_COMMIT..H1_TERMINAL_COMMIT (the working tree while the terminal is
 * open) it pins:
 *   - the change set is exactly the named files, and every edit to a
 *     historical test or fixture is exactly its reviewed acknowledgement;
 *   - `startRun` (every ECHE run) is untouched and still stamps v1; only
 *     `startSubjectRun`'s stamp moved, to v2;
 *   - the v1 engine, `candidates.ts` (K1/K2-bound), the gateway, robots,
 *     authority, classifier, subject modules and every migration are
 *     untouched;
 *   - the root runner changed by exactly the ruleset load and the candidate
 *     dispatch;
 *   - `signalRuleset.ts` / `rulesetCandidates.ts` open no socket, read no
 *     environment, issue one SELECT and one candidate INSERT respectively,
 *     and the persisted rule version is asserted to be the scoring one.
 */
import { describe, expect, it } from 'vitest';

import { codeOf, phaseRange, readCurrent, specifiers } from '../helpers/phaseRange.js';

/** The rel-* release candidate this slice branched from. */
const H1_BASE_COMMIT = '3a4ce31ff5005ba412a8a4876b11570b80125a9a';

/** Pinned by the REL harvest pin commit to this slice's own commit (closed range). */
const H1_TERMINAL_COMMIT: string | null = 'b3e8f4212c9f8d819b5e786d69fb4aac2cdd2fb1';

const ORCH = 'src/orgunits/orchestrator/';
const NEW_MODULES = [`${ORCH}rulesetCandidates.ts`, `${ORCH}signalRuleset.ts`];
const ROOT_RUNNER = `${ORCH}rootRunner.ts`;

/**
 * SHA-256 of JSON {removed, added} of each historical file's `git diff
 * --unified=0` lines. Reviewed as:
 *   R8 execution  - an ECHE root on a subject run is now refused earlier
 *                   (RUN_RULE_VERSION_ROOT_SCOPE_MISMATCH); the run-scope
 *                   foreign key is proved by a direct write instead
 *   R9 pack       - regenerated by its own generator (R9_WRITE_FIXTURE_PACK=1):
 *                   signalRuleVersion v1 -> v2, language-scored candidates
 *   v7 frontier   - one type annotation widened; behaviour unchanged
 *   B3.0 guard    - the fake pool answers the run's rule-version read (v1:
 *                   every root there is ECHE); one assertion pins that read
 *                   immediately before the gateway's run read
 */
const ACKNOWLEDGED_EDITS: Readonly<Record<string, string>> = {
  'src/test/integration/subjectResearchExecutionR8.test.ts':
    'f0c0af7747601e8e87a3608b28735d53815dfdc06100122435c977b2c22654af',
  'src/test/fixtures/globalR9/research-pack.json':
    '084cdd1b0e21d4dab448caf30182b4d1a6314b29a4dcf07b9a6b87b314dc9609',
  'src/test/unit/researchCohortGuardB30.test.ts':
    '89ac91ce19b153d17eb2d786d6abc7b06679bd34b8aec25be79bb2c666835dea',
  'src/test/harness/frontierReplay/v7Frontier.ts':
    '64b2b134d572ce9b17eae51572dc7f7d7b861f4065a2c9a328619bb495ad248b',
};

const AUTHORISED_CHANGESET = [
  `M\t${ORCH}frontier.ts`,
  `M\t${ROOT_RUNNER}`,
  `M\t${ORCH}run.ts`,
  'M\tsrc/orgunits/signals/scoreV2.ts',
  ...NEW_MODULES.map((f) => `A\t${f}`),
  ...Object.keys(ACKNOWLEDGED_EDITS).map((f) => `M\t${f}`),
  'A\tsrc/test/firewall/relHarvestH1SignalRuleset.firewall.test.ts',
  'A\tsrc/test/helpers/phaseRange.ts',
  'A\tsrc/test/helpers/relSubjectHarness.ts',
  'A\tsrc/test/integration/relHarvestSignalRulesetPerRun.test.ts',
  'A\tsrc/test/unit/relHarvestSignalRulesetPerRun.test.ts',
].sort();

const h1 = phaseRange(H1_BASE_COMMIT, H1_TERMINAL_COMMIT);

describe.skipIf(!h1.available)('REL harvest H1: the change set over its own range', () => {
  it('is exactly the named files, deleting and renaming nothing', () => {
    expect(h1.changeset()).toEqual(AUTHORISED_CHANGESET);
  });

  it('edits each historical file by exactly its reviewed acknowledgement', () => {
    for (const [path, digest] of Object.entries(ACKNOWLEDGED_EDITS)) {
      expect(h1.editDigest(path), path).toBe(digest);
    }
  });

  it('leaves the v1 engine, candidates.ts, web, classifier, subject modules and migrations untouched', () => {
    const touched = h1
      .changeset()
      .filter((l) =>
        /\t(migrations\/|src\/orgunits\/(web|classify|subject\w*|sourceDiscovery|identity)\/|src\/orgunits\/signals\/(?!scoreV2\.ts)|src\/orgunits\/orchestrator\/(candidates|orchestrate|pageCollection|researchCohortGuard)\.ts|src\/cli\/|src\/config\/|src\/db\/|package)/.test(
          l,
        ),
      );
    expect(touched).toEqual([]);
  });

  it('changes run.ts only by the subject run stamp: startRun is byte-identical', () => {
    const { removed, added } = h1.diffLines(`${ORCH}run.ts`);
    expect(removed).toEqual([
      '    [input.networkVantage, FETCH_POLICY_VERSION, ORGUNIT_SIGNAL_RULE_VERSION, input.admissionId],',
    ]);
    expect(added.filter((l) => !/^\s*(\*|\/\*\*|\*\/)/.test(l))).toEqual([
      "import { SUBJECT_RUN_SIGNAL_RULE_VERSION } from './signalRuleset.js';",
      '    [',
      '      input.networkVantage,',
      '      FETCH_POLICY_VERSION,',
      '      SUBJECT_RUN_SIGNAL_RULE_VERSION,',
      '      input.admissionId,',
      '    ],',
    ]);
    const run = codeOf(h1.sourceOf(`${ORCH}run.ts`));
    expect(run).toMatch(
      /export async function startRun\([\s\S]*?\[\s*input\.networkVantage,\s*FETCH_POLICY_VERSION,\s*ORGUNIT_SIGNAL_RULE_VERSION,\s*input\.dryRun \?\? false,\s*\]/,
    );
  });

  it('changes the root runner by exactly the ruleset load and the candidate dispatch', () => {
    const { removed, added } = h1.diffLines(ROOT_RUNNER);
    expect(removed).toEqual([
      '  const frontier: Frontier = createFrontier();',
      '  const candidates = await scoreAndPersistCandidates(pool, runId, candidateInputs);',
    ]);
    expect(added.filter((l) => !/^\s*\/\//.test(l))).toEqual([
      "import { scoreAndPersistCandidatesWithRuleset } from './rulesetCandidates.js';",
      "import { loadRunSignalRuleset, SIGNAL_RULESET_V1 } from './signalRuleset.js';",
      '  const ruleset = await loadRunSignalRuleset(pool, runId, resolved);',
      '  const frontier: Frontier = createFrontier(ruleset.scoreFrontierUrl);',
      '  const candidates =',
      '    ruleset === SIGNAL_RULESET_V1',
      '      ? await scoreAndPersistCandidates(pool, runId, candidateInputs)',
      '      : await scoreAndPersistCandidatesWithRuleset(pool, runId, candidateInputs, ruleset);',
    ]);
  });

  it('changes scoreV2.ts by its module comment only', () => {
    const { removed, added } = h1.diffLines('src/orgunits/signals/scoreV2.ts');
    for (const line of [...removed, ...added]) expect(line).toMatch(/^ \*/);
  });
});

describe('REL harvest H1: the ruleset modules are narrow and truthful', () => {
  it('import only the signal engines, the candidate types and pg', () => {
    expect(specifiers(codeOf(readCurrent(`${ORCH}signalRuleset.ts`))).sort()).toEqual(
      [
        '../signals/score.js',
        '../signals/scoreV2.js',
        '../signals/types.js',
        '../signals/typesV2.js',
        'pg',
      ].sort(),
    );
    expect(specifiers(codeOf(readCurrent(`${ORCH}rulesetCandidates.ts`))).sort()).toEqual(
      ['../signals/types.js', './candidates.js', './signalRuleset.js', 'pg'].sort(),
    );
  });

  it('open no socket, read no environment or clock, and call no gateway', () => {
    for (const file of NEW_MODULES) {
      const code = codeOf(readCurrent(file));
      expect(code, file).not.toMatch(
        /\bfetch\s*\(|node:(net|tls|http|https|dns|fs|child_process)|process\.env|Date\.now|Math\.random|executeWebAttempt|authoriseAndFetchPage|claude-agent-sdk|anthropic/i,
      );
    }
  });

  it('signalRuleset issues one SELECT of the run stamp and writes nothing', () => {
    const code = codeOf(readCurrent(`${ORCH}signalRuleset.ts`));
    expect(code).not.toMatch(/\b(INSERT|UPDATE|DELETE|TRUNCATE|ALTER|GRANT)\b\s/);
    const statements = [...code.matchAll(/`(\s*SELECT[\s\S]*?)`/g)].map((m) => m[1]!.trim());
    expect(statements).toEqual(['SELECT rule_version FROM orgunit_research_runs WHERE id = $1']);
    // Unknown versions are refused, never defaulted; the scope decides the version.
    expect(code).toMatch(/throw new RunSignalRulesetRefusal\(\s*'RUN_RULE_VERSION_UNSUPPORTED'/);
    expect(code).toMatch(/'RUN_RULE_VERSION_ROOT_SCOPE_MISMATCH'/);
  });

  it('rulesetCandidates writes only candidate rows, with the version that scored them', () => {
    const code = codeOf(readCurrent(`${ORCH}rulesetCandidates.ts`));
    const writes = [...code.matchAll(/\b(INSERT INTO|UPDATE|DELETE FROM|TRUNCATE)\s+(\w+)/g)].map(
      (m) => `${m[1]} ${m[2]}`,
    );
    expect(writes).toEqual(['INSERT INTO orgunit_page_candidates']);
    expect(code).toMatch(
      /if \(result\.ruleVersion !== ruleset\.ruleVersion\) \{\s*throw new Error\(/,
    );
    expect(code).toMatch(/VALUES \(\$1,\$2,\$3,\$4,NULL,\$5,\$6,\$7,\$8,\$9\)/);
  });

  it('candidates.ts still scores only with v1, and the frontier defaults to v1', () => {
    const candidates = codeOf(readCurrent(`${ORCH}candidates.ts`));
    expect(specifiers(candidates)).not.toContain('../signals/scoreV2.js');
    expect(candidates).toMatch(
      /import \{ scoreFetchedPageCandidate \} from '\.\.\/signals\/score\.js';/,
    );
    const frontier = codeOf(readCurrent(`${ORCH}frontier.ts`));
    expect(frontier).toMatch(
      /constructor\(private readonly scoreUrl: FrontierScorer = scoreFrontierUrl\) \{\}/,
    );
    expect(frontier).toMatch(
      /export function createFrontier\(scoreUrl: FrontierScorer = scoreFrontierUrl\): Frontier/,
    );
  });
});
